export function getEvidenceById(id: string): AcademicEvidence | undefined {
  return ACADEMIC_EVIDENCE_LIBRARY.find((e) => e.id.toLowerCase() === id.toLowerCase());
}

export function searchEvidence(query: string): AcademicEvidence[] {
  const q = query.toLowerCase();
  return ACADEMIC_EVIDENCE_LIBRARY.filter(
    (e) =>
      e.claim.toLowerCase().includes(q) ||
      (e.author && e.author.toLowerCase().includes(q)) ||
      e.title.toLowerCase().includes(q) ||
      e.id.toLowerCase().includes(q)
  );
}
